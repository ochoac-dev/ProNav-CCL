import type { ScanResult } from "../types.js";
import { slugify } from "../app/appData.js";
import { buildLearningData, type AppLearningData, type ExplanationDepth } from "../app/explanationData.js";
import { summarizeProjectMemory, type ProjectBrainEntry, type ProjectMemory } from "../memory/projectMemory.js";

export type HandoffAgent = "codex" | "claude" | "cursor" | "copy";

export type HandoffTaskType = "build-feature" | "fix-bug" | "explain-code" | "refactor" | "write-tests" | "review";

export interface HandoffRequest {
  agent: HandoffAgent;
  taskType: HandoffTaskType;
  goal: string;
  scope?: string;
  memory?: ProjectMemory;
  explanationDepth?: ExplanationDepth;
  excludedBrainEntryIds?: string[];
}

export interface HandoffResult {
  slug: string;
  agent: HandoffAgent;
  taskType: HandoffTaskType;
  goal: string;
  scope: string | null;
  relevantFiles: string[];
  prompt: string;
  markdown: string;
  projectBrainEntries: ProjectBrainEntry[];
}

export function buildHandoff(scan: ScanResult, request: HandoffRequest): HandoffResult {
  const goal = normalizeGoal(request.goal);
  const scope = request.scope?.trim() || null;
  const slug = slugify(goal).slice(0, 80) || "handoff-task";
  const relevantFiles = collectRelevantFiles(scan, scope);
  const agentLabel = agentDisplayName(request.agent);
  const taskLabel = taskTypeLabel(request.taskType);
  const learning = buildLearningData(scan);
  const explanationDepth = request.explanationDepth ?? null;
  const projectBrainEntries = selectProjectBrainEntries(
    request.memory,
    learning,
    relevantFiles,
    scope,
    request.excludedBrainEntryIds ?? []
  );
  const explanationLine = explanationDepth
    ? `Use ${depthLabel(explanationDepth)}-level explanations when explaining code, tradeoffs, and validation.`
    : "";
  const prompt = [
    `Use ${agentLabel} to ${taskLabel.toLowerCase()} in this local repo.`,
    "",
    `Goal: ${goal}`,
    `Repo: ${scan.profile.repoRoot}`,
    scope ? `Scope: ${scope}` : "Scope: use the bounded context below",
    explanationLine,
    "",
    "Read the handoff packet first, then inspect only the relevant files unless the task requires expanding scope.",
    request.memory ? "Use the Project Memory section for recent notes, scan changes, and validation history." : "",
    "Do not edit protected paths or generated dependency/build folders.",
    "Run the listed validation checks before reporting completion."
  ].filter(Boolean).join("\n");

  return {
    slug,
    agent: request.agent,
    taskType: request.taskType,
    goal,
    scope,
    relevantFiles,
    prompt,
    projectBrainEntries,
    markdown: renderHandoffMarkdown(scan, {
      agentLabel,
      taskLabel,
      goal,
      scope,
      relevantFiles,
      prompt,
      memory: request.memory,
      learning,
      explanationDepth,
      projectBrainEntries
    })
  };
}

function renderHandoffMarkdown(
  scan: ScanResult,
  context: {
    agentLabel: string;
    taskLabel: string;
    goal: string;
    scope: string | null;
    relevantFiles: string[];
    prompt: string;
    memory?: ProjectMemory;
    learning: AppLearningData;
    explanationDepth: ExplanationDepth | null;
    projectBrainEntries: ProjectBrainEntry[];
  }
): string {
  return [
    `# Agent Handoff: ${context.goal}`,
    "",
    "Generated by ProNav from a read-only local repo scan.",
    "",
    "## Plain-English Goal",
    "",
    context.goal,
    "",
    "## Coding Agent",
    "",
    `- Agent: ${context.agentLabel}`,
    `- Task type: ${context.taskLabel}`,
    `- Repo: \`${scan.profile.repoRoot}\``,
    `- Project type: \`${scan.detection.type}\``,
    `- Scope: ${context.scope ? `\`${context.scope}\`` : "bounded context below"}`,
    "",
    "## Friendly Project Context",
    "",
    `- Files scanned: ${scan.generic.totalFiles}`,
    `- Documents found: ${scan.documents.totalDocuments}`,
    `- Detected capabilities: ${scan.detection.detectedCapabilities.join(", ")}`,
    `- Main language groups: ${Object.entries(scan.generic.languageCounts)
      .slice(0, 6)
      .map(([name, count]) => `${name} (${count})`)
      .join(", ") || "none detected"}`,
    "",
    "## Relevant Files",
    "",
    ...bulletList(context.relevantFiles, "No narrow file matches were found. Start with the repo map and docs."),
    "",
    "## Project Documents",
    "",
    ...bulletList(scan.documents.files.slice(0, 10).map((file) => file.path), "No documents detected."),
    ...renderExplanationContext(context.learning, context.explanationDepth, context.relevantFiles),
    ...renderProjectBrainSection(context.projectBrainEntries),
    ...renderMemorySection(context.memory),
    "",
    "## Validation Checks",
    "",
    ...bulletList(scan.profile.validationCommands, "No validation commands configured."),
    "",
    "## Protected Paths",
    "",
    "- Do not edit protected paths or generated dependency/build folders unless the user explicitly asks.",
    ...bulletList(scan.profile.protectedPaths, "No protected paths configured."),
    "",
    "## Ready-To-Paste Prompt",
    "",
    "```text",
    context.prompt,
    "```"
  ].join("\n");
}

export function selectProjectBrainEntries(
  memory: ProjectMemory | undefined,
  learning: AppLearningData,
  relevantFiles: string[],
  scope: string | null,
  excludedBrainEntryIds: string[] = []
): ProjectBrainEntry[] {
  if (!memory?.projectBrain?.length) return [];

  const excluded = new Set(excludedBrainEntryIds);
  const relevant = new Set(relevantFiles);
  const relevantConcepts = new Set(
    relevantFiles.flatMap((file) => learning.fileExplanations[file]?.conceptIds ?? [])
  );

  return memory.projectBrain
    .filter((entry) => (entry.status === "approved" || entry.status === "pinned") && !excluded.has(entry.id))
    .filter((entry) => brainEntryMatches(entry, scope, relevant, relevantConcepts))
    .sort((a, b) => brainStatusWeight(b.status) - brainStatusWeight(a.status) || b.updatedAt.localeCompare(a.updatedAt))
    .slice(0, 8);
}

function renderProjectBrainSection(entries: ProjectBrainEntry[]): string[] {
  if (entries.length === 0) return [];

  return [
    "",
    "## Human-Approved Project Brain",
    "",
    ...plainBulletList(entries.map(renderProjectBrainEntry), "No approved Project Brain entries matched this handoff.")
  ];
}

function renderProjectBrainEntry(entry: ProjectBrainEntry): string {
  const scope = entry.scope ? ` Scope: ${entry.scope}.` : "";
  const paths = entry.paths.length ? ` Paths: ${entry.paths.slice(0, 4).join(", ")}.` : "";
  return `${projectBrainKindLabel(entry.kind)} | ${entry.status}: ${entry.title}. ${entry.body}${scope}${paths}`;
}

function brainEntryMatches(
  entry: ProjectBrainEntry,
  scope: string | null,
  relevantFiles: Set<string>,
  relevantConcepts: Set<string>
): boolean {
  if (!entry.scope && entry.paths.length === 0 && entry.conceptIds.length === 0) return true;
  if (entry.scope && scope && pathMatches(entry.scope, scope)) return true;
  if (entry.scope && [...relevantFiles].some((file) => pathMatches(file, entry.scope ?? ""))) return true;
  if (entry.paths.some((path) => (scope && pathMatches(path, scope)) || relevantFiles.has(path))) return true;
  if (entry.conceptIds.some((id) => relevantConcepts.has(id))) return true;
  return false;
}

function pathMatches(left: string, right: string): boolean {
  const a = left.toLowerCase();
  const b = right.toLowerCase();
  return a === b || a.startsWith(`${b}/`) || b.startsWith(`${a}/`) || a.includes(b) || b.includes(a);
}

function brainStatusWeight(status: ProjectBrainEntry["status"]): number {
  return status === "pinned" ? 2 : status === "approved" ? 1 : 0;
}

function projectBrainKindLabel(kind: ProjectBrainEntry["kind"]): string {
  switch (kind) {
    case "module-card":
      return "Module Card";
    case "decision":
      return "Decision";
    case "constraint-risk":
      return "Constraint/Risk";
    case "open-question":
      return "Open Question";
  }
}

function renderExplanationContext(
  learning: AppLearningData,
  depth: ExplanationDepth | null,
  relevantFiles: string[]
): string[] {
  if (!depth) return [];

  const relevant = new Set(relevantFiles);
  const concepts = learning.concepts.filter((concept) => concept.paths.some((path) => relevant.has(path))).slice(0, 8);
  return [
    "",
    "## Explanation Context",
    "",
    `- Explanation depth: ${depthLabel(depth)}`,
    `- Project explanation: ${learning.projectExplanation[depth]}`,
    "",
    "### Detected Concepts",
    "",
    ...plainBulletList(
      concepts.map((concept) => `${concept.label}: ${concept.description} Paths: ${concept.paths.slice(0, 3).join(", ")}`),
      "No high-signal concepts were detected in the bounded file list."
    )
  ];
}

function collectRelevantFiles(scan: ScanResult, scope: string | null): string[] {
  const candidates = [
    ...Object.values(scan.features).flatMap((feature) => feature.files.map((file) => file.path)),
    ...scan.generic.sampleFiles,
    ...scan.documents.files.map((file) => file.path)
  ];
  const filtered = scope ? candidates.filter((path) => path.startsWith(scope) || path.includes(scope)) : candidates;
  const narrowed = filtered.length > 0 ? filtered : candidates;

  return [...new Set(narrowed)].slice(0, 30);
}

function normalizeGoal(goal: string): string {
  const value = goal.trim();
  if (!value) {
    throw new Error("Handoff goal is required.");
  }

  return value;
}

function agentDisplayName(agent: HandoffAgent): string {
  switch (agent) {
    case "codex":
      return "Codex";
    case "claude":
      return "Claude Code";
    case "cursor":
      return "Cursor";
    case "copy":
      return "Copy Prompt";
  }
}

function taskTypeLabel(taskType: HandoffTaskType): string {
  switch (taskType) {
    case "build-feature":
      return "Build Feature";
    case "fix-bug":
      return "Fix Bug";
    case "explain-code":
      return "Explain Code";
    case "refactor":
      return "Refactor";
    case "write-tests":
      return "Write Tests";
    case "review":
      return "Review";
  }
}

function depthLabel(depth: ExplanationDepth): string {
  switch (depth) {
    case "builder":
      return "Builder";
    case "developer":
      return "Developer";
    case "senior":
      return "Senior";
  }
}

function bulletList(values: string[], emptyText: string): string[] {
  return values.length === 0 ? [`- ${emptyText}`] : values.map((value) => `- \`${value}\``);
}

function renderMemorySection(memory: ProjectMemory | undefined): string[] {
  if (!memory) return [];

  const hasMemory =
    memory.scans.length > 0 ||
    memory.validations.length > 0 ||
    memory.handoffs.length > 0 ||
    memory.notes.length > 0 ||
    memory.projectBrain.length > 0;
  if (!hasMemory) return [];

  const summary = summarizeProjectMemory(memory);
  return [
    "",
    "## Project Memory",
    "",
    ...renderScanMemory(summary),
    `- Validation history: ${summary.validationCounts.passed} passed, ${summary.validationCounts.failed} failed, ${summary.validationCounts.timedOut} timed out`,
    "",
    "### Recent Notes",
    "",
    ...plainBulletList(
      memory.notes.slice(0, 5).map((note) => `${formatMemoryDate(note.createdAt)}: ${note.text}`),
      "No notes saved yet."
    ),
    "",
    "### Recent Validation Runs",
    "",
    ...plainBulletList(memory.validations.slice(0, 5).map(renderValidationMemory), "No validation runs recorded yet."),
    "",
    "### Recent Handoffs",
    "",
    ...plainBulletList(memory.handoffs.slice(0, 5).map(renderHandoffMemory), "No prior handoffs recorded yet.")
  ];
}

function renderScanMemory(summary: ReturnType<typeof summarizeProjectMemory>): string[] {
  if (!summary.latestScan) {
    return ["- No scan history recorded yet."];
  }

  if (!summary.previousScan || !summary.scanChange) {
    return [`- Latest scan: ${summary.latestScan.files} files, ${summary.latestScan.documents} docs, ${summary.latestScan.dirtyEntries} git status entries`];
  }

  return [
    `- Files changed since last scan: ${formatSigned(summary.scanChange.files)}`,
    `- Documents changed since last scan: ${formatSigned(summary.scanChange.documents)}`,
    `- Git status entries changed since last scan: ${formatSigned(summary.scanChange.dirtyEntries)}`
  ];
}

function renderValidationMemory(validation: ProjectMemory["validations"][number]): string {
  const status = validation.timedOut ? "timed out" : validation.exitCode === 0 ? "passed" : "failed";
  return `${formatMemoryDate(validation.createdAt)}: ${validation.command} | ${status} | exit ${validation.exitCode} | ${Math.round(validation.durationMs / 1000)}s`;
}

function renderHandoffMemory(handoff: ProjectMemory["handoffs"][number]): string {
  return `${formatMemoryDate(handoff.createdAt)}: ${handoff.agent} ${handoff.taskType} | ${handoff.goal}`;
}

function plainBulletList(values: string[], emptyText: string): string[] {
  return values.length === 0 ? [`- ${emptyText}`] : values.map((value) => `- ${value}`);
}

function formatSigned(value: number): string {
  return value > 0 ? `+${value}` : String(value);
}

function formatMemoryDate(value: string): string {
  return value.slice(0, 10) || "Unknown date";
}
